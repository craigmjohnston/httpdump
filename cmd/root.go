package cmd

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"github.com/spf13/cobra"
	"io"
	"io/fs"
	"net/http"
	"os"
	"os/exec"
	"strings"
	"time"
)

var port *int
var jsonFilenamePath *string
var execCommand *string

var rootCmd = func() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "httpdump",
		Short: "Simple web server that dumps all requests it gets to the file system",
		Run: func(cmd *cobra.Command, args []string) {
			if port == nil {
				panic("port required")
			}

			h := handler{}
			if *execCommand != "" {
				h.execQueue = make(chan []byte, 100)
				go runExecQueue(*execCommand, h.execQueue)
			}

			fmt.Printf("Running httpdump on port %d\n", *port)
			err := http.ListenAndServe(fmt.Sprintf("0.0.0.0:%d", *port), h)
			if err != nil {
				panic(err)
			}
		},
	}

	port = cmd.Flags().Int("port", 80, "Port to listen on")
	jsonFilenamePath = cmd.Flags().String("jsonFilenameKey", "", "A JSON key to build the filename from")
	execCommand = cmd.Flags().String("exec", "", "A shell command to run for each request, with the request body on stdin")

	return cmd
}()

func Execute() {
	if err := rootCmd.Execute(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type handler struct {
	execQueue chan []byte
}

func (h handler) ServeHTTP(res http.ResponseWriter, req *http.Request) {
	sb := strings.Builder{}

	sb.WriteString("# Generated by httpdump - right now these requests aren't replayable because the URLs are prettified\n\n")

	sb.WriteString(req.Method)
	sb.WriteRune(' ')
	sb.WriteString(req.URL.String())
	sb.WriteString("\n")

	for key, value := range req.Header {
		sb.WriteString(key)
		sb.WriteString(": ")
		sb.WriteString(strings.Join(value, ", "))
		sb.WriteString("\n")
	}
	sb.WriteRune('\n')

	body, err := io.ReadAll(req.Body)
	if err != nil {
		panic(err)
	}

	sb.WriteString(string(body))
	err = req.Body.Close()
	if err != nil {
		panic(err)
	}

	prefix := ""
	if jsonFilenamePath != nil && *jsonFilenamePath != "" {
		var out map[string]any
		err = json.Unmarshal(body, &out)
		if err != nil {
			panic(err)
		}
		value := out[*jsonFilenamePath].(string)
		prefix = fmt.Sprintf("%s_", value)
	}

	timestamp := time.Now().UnixMicro()
	filepath, err := writeNewFile(fmt.Sprintf("./%s%d", prefix, timestamp), []byte(sb.String()))
	if err != nil {
		panic(err)
	}

	fmt.Printf("%s %s saved to %s\n", req.Method, req.URL.String(), filepath)

	if h.execQueue != nil {
		h.execQueue <- body
	}

	res.WriteHeader(http.StatusOK)
}

// runExecQueue runs the command once per queued body, one at a time, so outputs never interleave.
func runExecQueue(command string, queue <-chan []byte) {
	for body := range queue {
		runExecCommand(command, body)
	}
}

func runExecCommand(command string, body []byte) {
	c := exec.Command("sh", "-c", command)
	c.Stdin = bytes.NewReader(body)
	c.Stdout = os.Stdout
	c.Stderr = os.Stderr

	err := c.Run()
	if err != nil {
		fmt.Fprintf(os.Stderr, "exec %q: %s\n", command, err)
	}
}

func writeNewFile(name string, data []byte) (string, error) {
	path := name + ".http"
	for i := 1; ; i++ {
		f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, os.ModePerm)
		if errors.Is(err, fs.ErrExist) {
			path = fmt.Sprintf("%s-%d.http", name, i)
			continue
		}
		if err != nil {
			return "", err
		}

		_, err = f.Write(data)
		if closeErr := f.Close(); err == nil {
			err = closeErr
		}
		return path, err
	}
}
